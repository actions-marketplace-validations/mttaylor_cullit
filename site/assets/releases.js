/* releases.js — Release notes page logic (CSP-safe, no inline handlers) */
(function () {
  'use strict';

  var releasesEl = document.getElementById('releases');
  var providerBar = document.getElementById('providerBar');
  var activeProvider = 'anthropic';
  var releasesData = [];

  // --- Hamburger ---
  if (window.CullitSite) window.CullitSite.initMobileNav();

  // --- Provider switching ---
  providerBar.addEventListener('click', function (e) {
    var btn = e.target.closest('.provider-btn');
    if (!btn) return;
    providerBar.querySelectorAll('.provider-btn').forEach(function (b) { b.classList.remove('active'); });
    btn.classList.add('active');
    activeProvider = btn.dataset.provider;
    renderReleases();
  });

  var md2html = (window.CullitSite && window.CullitSite.markdownToHtml)
    ? window.CullitSite.markdownToHtml
    : function (s) { return s ? '<p>' + s + '</p>' : ''; };

  // --- Render ---
  function renderReleases() {
    if (releasesData.length === 0) {
      releasesEl.innerHTML = '<div class="loading"><p>No releases found.</p></div>';
      return;
    }

    releasesEl.innerHTML = releasesData.map(function (r, i) {
      var provData = r.providers ? r.providers[activeProvider] : null;
      var content = (provData && provData.html) || md2html(provData && provData.markdown);
      var hasProvider = !!(provData && (provData.markdown || provData.html));

      var patches = (r._patches || []).map(function (p) {
        var pProvData = p.providers ? p.providers[activeProvider] : null;
        var pContent = (pProvData && pProvData.html) || md2html(pProvData && pProvData.markdown);
        var pHasProvider = !!(pProvData && (pProvData.markdown || pProvData.html));
        return '<div class="patch-card" data-version="' + p.version + '">' +
            '<div class="patch-header" data-toggle-parent>' +
              '<span class="patch-version">' + p.version + '</span>' +
              '<div class="release-meta">' +
                '<span class="release-stats">' + p.commits + ' commits · ' + p.filesChanged + ' files</span>' +
                '<span class="release-date">' + p.date + '</span>' +
                '<span class="release-chevron">▶</span>' +
              '</div>' +
            '</div>' +
            '<div class="patch-body">' +
              '<div class="provider-label">' +
                '<span class="provider-dot ' + activeProvider + '"></span>' +
                'Generated by ' + (activeProvider === 'template' ? 'cullit template engine' : activeProvider + ' via cullit') +
                ((pProvData && pProvData.generatedAt) ? ' · ' + pProvData.generatedAt.split('T')[0] : '') +
              '</div>' +
              '<div class="release-content">' +
                (pHasProvider ? pContent : '<p style="color:var(--text-dim)"><em>Release notes not yet generated for this provider.</em></p>') +
              '</div>' +
            '</div>' +
          '</div>';
      }).join('');

      var patchesHtml = patches ? '<div class="patch-list">' + patches + '</div>' : '';

      return '<div class="release-card' + (i === 0 ? ' open' : '') + '" data-version="' + r.version + '">' +
          '<div class="release-header" role="button" aria-expanded="' + (i === 0 ? 'true' : 'false') + '" data-toggle-release>' +
            '<span class="release-version">' + r.version + '</span>' +
            '<div class="release-meta">' +
              '<span class="release-stats">' + r.commits + ' commits · ' + r.filesChanged + ' files</span>' +
              '<span class="release-date">' + r.date + '</span>' +
              '<span class="release-chevron">▶</span>' +
            '</div>' +
          '</div>' +
          '<div class="release-body">' +
            '<div class="provider-label">' +
              '<span class="provider-dot ' + activeProvider + '"></span>' +
              'Generated by ' + (activeProvider === 'template' ? 'cullit template engine' : activeProvider + ' via cullit') +
              ((provData && provData.generatedAt) ? ' · ' + provData.generatedAt.split('T')[0] : '') +
            '</div>' +
            '<div class="release-content">' +
              (hasProvider ? content : '<p style="color:var(--text-dim)"><em>Release notes not yet generated for this provider.</em></p>') +
            '</div>' +
          '</div>' +
          patchesHtml +
        '</div>';
    }).join('');
  }

  // --- Event delegation for dynamically-rendered cards ---
  releasesEl.addEventListener('click', function (e) {
    var patchHeader = e.target.closest('[data-toggle-parent]');
    if (patchHeader) {
      patchHeader.parentElement.classList.toggle('open');
      return;
    }
    var releaseHeader = e.target.closest('[data-toggle-release]');
    if (releaseHeader) {
      var card = releaseHeader.parentElement;
      var isOpen = card.classList.toggle('open');
      releaseHeader.setAttribute('aria-expanded', String(isOpen));
    }
  });

  // --- Load data ---
  async function loadReleases() {
    try {
      var indexRes = await fetch('releases/index.json');
      if (!indexRes.ok) throw new Error('No index');
      var index = await indexRes.json();

      var promises = index.map(async function (entry) {
        var main;
        try {
          var res = await fetch('releases/' + entry.version + '.json');
          main = res.ok ? await res.json() : entry;
        } catch (err) {
          main = entry;
        }

        var patches = entry.patches || [];
        var patchPromises = patches.map(async function (p) {
          try {
            var res = await fetch('releases/' + p.version + '.json');
            return res.ok ? await res.json() : p;
          } catch (err) {
            return p;
          }
        });
        main._patches = await Promise.all(patchPromises);
        return main;
      });

      releasesData = await Promise.all(promises);
      renderReleases();
    } catch (err) {
      releasesEl.innerHTML = '<div class="loading"><p>No release notes found yet. Run <code>node scripts/generate-release-notes.mjs</code> to generate.</p></div>';
    }
  }

  loadReleases();
})();
